type DeepRecord<T> = {
  [K in keyof T]: T[K] extends (...args: any[]) => any
    ? T[K]
    : T[K] extends Array<infer U>
    ? Array<DeepRecord<U>>
    : T[K] extends object
    ? DeepRecord<T[K]>
    : string;
};

